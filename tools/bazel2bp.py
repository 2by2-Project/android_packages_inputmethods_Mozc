"""Imports the Mozc engine and its OSS data set into Soong.

Reads upstream Mozc's BUILD.bazel files (with a small Starlark emulator),
computes the closure needed for
  - //android/jni:mozc               -> libmozc.so (device, JNI)
  - //data_manager/oss:mozc_dataset_for_oss  -> mozc.data (generated at build
                                                time by host tools)
copies exactly those source files into the output directory and writes an
Android.bp next to them.

Usage:
  bazel2bp.py --mozc_src <mozc checkout>/src --out <repo>/native \
      [--usage_dict <dir containing usage_dict.txt>]
"""

import argparse
import collections
import os
import re
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import starlark  # pylint: disable=g-import-not-at-top

ROOTS = {
    'device': ['//android/jni:mozc'],
    'host': ['//data_manager/oss:mozc_dataset_for_oss'],
}

TARGET_SETTINGS = [
    '//bazel/cc_target_os:oss_android',
    '@platforms//os:android',
    '@platforms//cpu:arm64',
    '//:opt',
    '//:compiler_gcc_like',
]
# Host tools: defines (TARGET=oss_android) propagate to the exec
# configuration in Bazel, platform constraints do not.
HOST_SETTINGS = [
    '//bazel/cc_target_os:oss_android',
    '@platforms//os:linux',
    '@platforms//cpu:x86_64',
    '//:opt',
    '//:compiler_gcc_like',
]

ABSL_PREFIX = '@com_google_absl//'
# Abseil libraries missing from AOSP's external/abseil-cpp, replaced by
# modules defined in tools/native_prologue.bp (sources in tools/shims/).
ABSL_SUBSTITUTES = {
    '@com_google_absl//absl/log:flags': 'mozc_shim_absl_log_flags',
}
EXTERNAL_FILES = {
    '@ja_usage_dict//:usage_dict.txt': 'third_party/japanese_usage_dictionary/usage_dict.txt',
    '@zip_code_ken_all//:KEN_ALL.CSV': 'third_party/zip_code/KEN_ALL.CSV',
    '@zip_code_jigyosyo//:JIGYOSYO.CSV': 'third_party/zip_code/JIGYOSYO.CSV',
}

CC_KINDS = ('cc_library',)
GEN_KINDS = ('genrule', 'mozc_run_build_tool', 'run_binary')
HEADER_EXTS = ('.h', '.hpp', '.inc', '.inl')
CC_EXTS = ('.cc', '.cpp', '.c')

LICENSE_HEADER = """//
// Copyright (C) 2026 The 2by2 Project
//
// SPDX-License-Identifier: Apache-2.0
//
// DO NOT EDIT: generated by tools/bazel2bp.py from upstream Mozc %s
//
"""


def mod_name(label):
  pkg, name = split_label(label)
  s = 'mozc_%s_%s' % (pkg.replace('/', '_'), name)
  return re.sub(r'[^A-Za-z0-9_]', '_', s)


def split_label(label):
  assert label.startswith('//'), label
  pkg, _, name = label[2:].partition(':')
  if not name:
    name = pkg.rsplit('/', 1)[-1]
  return pkg, name


def norm_label(label, pkg):
  if label.startswith('@//'):
    label = label[1:]
  if label.startswith('@'):
    return label
  if label.startswith('//'):
    p, name = split_label(label)
    return '//%s:%s' % (p, name)
  if label.startswith(':'):
    return '//%s:%s' % (pkg, label[1:])
  return '//%s:%s' % (pkg, label)


class Converter(object):

  def __init__(self, src_root, version):
    self.src = src_root
    self.version = version
    self.loader = starlark.Loader(src_root)
    self.cfgs = {
        'device': starlark.Config('device', TARGET_SETTINGS),
        'host': starlark.Config('host', HOST_SETTINGS),
    }
    for c in self.cfgs.values():
      c.matches = self._matcher(c)
    self.needed = collections.defaultdict(set)  # label -> {cfg names}
    self.files = set()          # source files (relative to src root)
    self.out_index = {}         # 'pkg/file' -> producing label
    self.indexed_pkgs = set()
    self.alwayslink = set()

  # ---- configuration -----------------------------------------------------
  def _matcher(self, cfg):
    true = set(cfg.true)

    def matches(label):
      if label in true:
        return True
      if label.startswith('//'):
        t = self.target(label, missing_ok=True)
        if t is not None and t.kind == 'config_setting_group':
          any_of = t.attrs.get('match_any')
          all_of = t.attrs.get('match_all')
          if any_of:
            return any(matches(norm_label(x, t.pkg)) for x in any_of)
          if all_of:
            return all(matches(norm_label(x, t.pkg)) for x in all_of)
      return False
    return matches

  # ---- target lookup -----------------------------------------------------
  def target(self, label, missing_ok=False):
    pkg, _ = split_label(label)
    self.loader.load_package(pkg)
    self._index(pkg)
    t = self.loader.targets.get(label)
    if t is None and not missing_ok:
      raise KeyError(label)
    return t

  def _index(self, pkg):
    if pkg in self.indexed_pkgs:
      return
    self.indexed_pkgs.add(pkg)
    for t in list(self.loader.targets.values()):
      if t.pkg != pkg:
        continue
      for out in self.outs_of(t, None):
        self.out_index['%s/%s' % (pkg, out)] = t.label

  def attr(self, t, key, cfg, default=None):
    v = t.attrs.get(key, default)
    if cfg is None:
      # Unconfigured lookups (e.g. outputs) must not depend on select().
      return starlark.resolve(v, self.cfgs['device'])
    return starlark.resolve(v, self.cfgs[cfg])

  def run_tool_srcs(self, t, cfg):
    """Returns [(option, [labels])] of a mozc_run_build_tool target."""
    opts = self.attr(t, 'src_options', cfg) or []
    labels = self.attr(t, 'src_labels', cfg) or []
    grouped = collections.OrderedDict()
    for opt, label in zip(opts, labels):
      grouped.setdefault(opt, []).append(label)
    return list(grouped.items())

  def outs_of(self, t, cfg):
    if t.kind == 'genrule' or t.kind == 'run_binary':
      return list(self.attr(t, 'outs', cfg, []) or [])
    if t.kind == 'mozc_run_build_tool':
      return list((self.attr(t, 'outs', cfg, {}) or {}).values())
    return []

  def classify(self, label, pkg):
    """Returns ('target', label) | ('file', path) | ('gen', (label, path))."""
    label = norm_label(label, pkg)
    if label in EXTERNAL_FILES:
      return 'extfile', EXTERNAL_FILES[label]
    if label.startswith('@'):
      return 'external', label
    p, name = split_label(label)
    t = self.target(label, missing_ok=True)
    if t is not None:
      return 'target', label
    path = '%s/%s' % (p, name) if p else name
    if path in self.out_index:
      return 'gen', (self.out_index[path], path)
    if os.path.isfile(os.path.join(self.src, path)):
      return 'file', path
    raise KeyError('cannot resolve %s' % label)

  # ---- closure -----------------------------------------------------------
  def walk(self):
    todo = [(l, c) for c, ls in ROOTS.items() for l in ls]
    while todo:
      label, cfg = todo.pop()
      if cfg in self.needed[label]:
        continue
      self.needed[label].add(cfg)
      t = self.target(label)
      for dep, dep_cfg in self.deps_of(t, cfg):
        todo.append((dep, dep_cfg))

  def deps_of(self, t, cfg):
    """Yields (label, cfg) of targets t depends on and records files."""
    k = t.kind
    keys_same = ['srcs', 'hdrs', 'textual_hdrs', 'deps', 'data']
    keys_host = []
    if k in GEN_KINDS:
      keys_host = ['tools', 'tool', 'exec_tools']
      keys_same = ['srcs', 'positional_srcs', 'src_labels']
    if k == 'py_binary' or k == 'py_library':
      cfg = 'host'
    for key in keys_same + keys_host:
      dcfg = 'host' if key in keys_host else cfg
      v = self.attr(t, key, cfg)
      if v is None:
        continue
      if isinstance(v, str):
        v = [v]
      if isinstance(v, dict):  # mozc_run_build_tool srcs: {option: labels}
        v = [x for vs in v.values() for x in (vs if isinstance(vs, list) else [vs])]
      for item in v:
        kind, val = self.classify(item, t.pkg)
        if kind == 'target':
          tt = self.target(val)
          if tt.kind == 'filegroup':
            for f in self.attr(tt, 'srcs', dcfg) or []:
              fk, fv = self.classify(f, tt.pkg)
              if fk == 'file':
                self.files.add(fv)
              elif fk == 'gen':
                yield fv[0], dcfg
              elif fk == 'target':
                yield fv, dcfg
            continue
          yield val, dcfg
        elif kind == 'file':
          self.files.add(val)
        elif kind == 'gen':
          yield val[0], dcfg
    if k == 'cc_library' and t.attrs.get('alwayslink'):
      self.alwayslink.add(t.label)
    if k == 'cc_binary' and t.attrs.get('main'):
      pass
    if k in ('py_binary',) and t.attrs.get('main'):
      kind, val = self.classify(t.attrs['main'], t.pkg)
      if kind == 'file':
        self.files.add(val)
    if k == 'proto_library':
      pass

  # ---- emission ----------------------------------------------------------
  def src_ref(self, item, pkg, cfg):
    kind, val = self.classify(item, pkg)
    if kind == 'file' or kind == 'extfile':
      return 'file', val
    if kind == 'gen':
      return 'gen', (val[0], val[1])
    if kind == 'target':
      t = self.target(val)
      if t.kind == 'filegroup':
        return 'group', [self.src_ref(f, t.pkg, cfg)
                         for f in self.attr(t, 'srcs', cfg) or []]
      return 'target', val
    return kind, val

  def cc_module(self, t):
    cfgs = sorted(self.needed[t.label])
    per_cfg = {}
    for cfg in cfgs:
      m = collections.OrderedDict()
      srcs, gen_srcs, gen_hdrs, static_libs, whole, shared = [], [], [], [], [], []
      cflags = []
      for key in ('srcs', 'hdrs', 'textual_hdrs'):
        for item in self.attr(t, key, cfg) or []:
          for kind, val in self._flatten(self.src_ref(item, t.pkg, cfg)):
            if kind == 'file':
              if val.endswith(CC_EXTS) and key == 'srcs':
                srcs.append(val)
            elif kind == 'gen':
              glabel, path = val
              if path.endswith(CC_EXTS) and key == 'srcs':
                gen_srcs.append(':%s{%s}' % (mod_name(glabel), path))
              else:
                gen_hdrs.append(mod_name(glabel))
            elif kind == 'target' and self.target(val).kind in GEN_KINDS:
              gt = self.target(val)
              for out in self.outs_of(gt, cfg):
                path = '%s/%s' % (gt.pkg, out)
                if path.endswith(CC_EXTS) and key == 'srcs':
                  gen_srcs.append(':%s{%s}' % (mod_name(val), path))
                else:
                  gen_hdrs.append(mod_name(val))
      for item in self.attr(t, 'deps', cfg) or []:
        kind, val = self.classify(item, t.pkg)
        if kind == 'external':
          static_libs.extend(self.external_lib(val, cfg))
        elif kind == 'target':
          dt = self.target(val)
          if dt.kind in ('cc_library', 'cc_proto_library'):
            name = mod_name(val if dt.kind == 'cc_library' else self.proto_of(dt))
            if val in self.alwayslink:
              whole.append(name)
            else:
              static_libs.append(name)
          elif dt.kind == 'filegroup':
            pass
          else:
            raise ValueError('%s: unsupported dep %s (%s)' % (t.label, val, dt.kind))
      # `defines` propagate to all dependents: see generated_defines().
      for d in self.attr(t, 'local_defines', cfg) or []:
        cflags.append('-D' + d)
      for c in self.attr(t, 'copts', cfg) or []:
        if c.startswith('/'):
          continue
        cflags.append(c)
      for lo in self.attr(t, 'linkopts', cfg) or []:
        if lo == '-llog':
          shared.append('liblog')
        elif lo.startswith('-l'):
          shared.append('lib' + lo[2:])
      m['srcs'] = srcs + gen_srcs
      m['generated_headers'] = sorted(set(gen_hdrs))
      m['export_generated_headers'] = sorted(set(gen_hdrs))
      m['static_libs'] = static_libs
      m['whole_static_libs'] = whole
      m['shared_libs'] = shared
      # Bazel makes the headers of all deps visible transitively.
      m['export_static_lib_headers'] = static_libs + whole
      m['export_shared_lib_headers'] = list(shared)
      m['cflags'] = cflags
      per_cfg[cfg] = m
    return per_cfg

  def _flatten(self, ref):
    kind, val = ref
    if kind == 'group':
      for r in val:
        yield from self._flatten(r)
    else:
      yield kind, val

  def proto_of(self, cc_proto):
    deps = self.attr(cc_proto, 'deps', 'device')
    assert len(deps) == 1, cc_proto
    return norm_label(deps[0], cc_proto.pkg)

  def external_lib(self, label, cfg):
    if label in ABSL_SUBSTITUTES:
      return [ABSL_SUBSTITUTES[label]]
    if label.startswith(ABSL_PREFIX):
      path = label[len(ABSL_PREFIX):]
      p, _, name = path.partition(':')
      base = p.rsplit('/', 1)[-1]
      parts = p.split('/')[1:]  # drop the leading 'absl'
      if name and name != base:
        parts.append(name)
      return ['absl_' + '_'.join(parts)]
    if label == '@com_google_protobuf//:protobuf':
      return ['@protobuf']
    raise ValueError('unknown external dependency %s' % label)


  # ---- genrule translation -----------------------------------------------
  def gen_module(self, t):
    """Translates genrule / run_binary / mozc_run_build_tool to Soong."""
    cfg = 'host'
    pkg = t.pkg
    outs = ['%s/%s' % (pkg, o) for o in self.outs_of(t, cfg)]
    srcs = []      # Soong srcs entries (ordered, unique)
    tools = []     # Soong host tool module names
    tool_files = []

    def add_src(entry):
      if entry not in srcs:
        srcs.append(entry)
      return entry

    def tool_ref(label):
      label = norm_label(label, pkg)
      tt = self.target(label)
      if tt.kind not in ('cc_binary', 'py_binary'):
        raise ValueError('%s: unsupported tool %s' % (t.label, label))
      name = mod_name(label)
      if name not in tools:
        tools.append(name)
      return '$(location %s)' % name

    def file_refs(label, plural):
      """Returns Soong cmd text for $(location(s) label)."""
      nl = norm_label(label, pkg)
      if nl == t.label:
        return ' '.join('$(genDir)/' + o for o in outs)
      kind, val = self.classify(label, pkg)
      if kind in ('file', 'extfile'):
        return '$(location %s)' % add_src(val)
      if kind == 'gen':
        glabel, path = val
        if glabel == t.label:
          return '$(genDir)/' + path
        return '$(location %s)' % add_src(':%s{%s}' % (mod_name(glabel), path))
      if kind == 'target':
        tt = self.target(val)
        if tt.kind in ('cc_binary', 'py_binary'):
          return tool_ref(val)
        if tt.kind == 'filegroup':
          parts = [file_refs(norm_label(f, tt.pkg), True)
                   for f in self.attr(tt, 'srcs', cfg) or []]
          return ' '.join(parts)
        if tt.kind in GEN_KINDS:
          n = len(self.outs_of(tt, cfg))
          ref = add_src(':' + mod_name(val))
          return '$(%s %s)' % ('locations' if n > 1 else 'location', ref)
      raise ValueError('%s: cannot reference %s' % (t.label, label))

    def expand(text):
      text = re.sub(r'\$\((location|locations|execpath|execpaths|rootpath|rootpaths) ([^)]+)\)',
                    lambda m: file_refs(m.group(2).strip(), m.group(1).endswith('s')),
                    text)

      def at_d(m):
        f = m.group(1)
        path = '%s/%s' % (pkg, f)
        if path in outs:
          return '$(genDir)/' + path
        if path in self.out_index:
          return '$(location %s)' % add_src(':%s{%s}' % (mod_name(self.out_index[path]), path))
        raise ValueError('%s: unknown $(@D)/%s' % (t.label, f))
      text = re.sub(r'\$\((?:@D|RULEDIR)\)/([A-Za-z0-9_.\-/]+)', at_d, text)
      text = text.replace('$(@D)', '$(genDir)/' + pkg)
      text = text.replace('$(RULEDIR)', '$(genDir)/' + pkg)
      text = text.replace('$(SRCS)', '$(in)').replace('$<', '$(in)')
      text = text.replace('$(OUTS)', '$(out)').replace('$@', '$(out)')
      return text

    # Declared srcs first, so that $(in) matches Bazel's $(SRCS).
    declared = []
    for item in self.attr(t, 'srcs', cfg) or [] if t.kind != 'mozc_run_build_tool' else []:
      declared.append(item)

    def add_declared(item):
      kind, val = self.classify(item, pkg)
      if kind in ('file', 'extfile'):
        add_src(val)
      elif kind == 'gen':
        add_src(':%s{%s}' % (mod_name(val[0]), val[1]))
      elif kind == 'target':
        tt = self.target(val)
        if tt.kind == 'filegroup':
          for f in self.attr(tt, 'srcs', cfg) or []:
            add_declared(norm_label(f, tt.pkg))
        elif tt.kind in GEN_KINDS:
          add_src(':' + mod_name(val))
        else:
          raise ValueError('%s: bad src %s' % (t.label, val))
    for item in declared:
      add_declared(item)

    if t.kind == 'genrule':
      cmd = expand(' '.join(self.attr(t, 'cmd', cfg).split()))
      for tl in self.attr(t, 'tools', cfg) or []:
        tool_ref(tl)
    elif t.kind == 'run_binary':
      args = [expand(a) for a in self.attr(t, 'args', cfg) or []]
      env = self.attr(t, 'env', cfg) or {}
      cmd = ' '.join(['%s=%s' % kv for kv in sorted(env.items())] +
                     [tool_ref(self.attr(t, 'tool', cfg))] + args)
    else:  # mozc_run_build_tool
      parts = [tool_ref(self.attr(t, 'tool', cfg))]
      parts += [expand(a) for a in self.attr(t, 'args', cfg) or []]
      for opt, labels in self.run_tool_srcs(t, cfg):
        parts.append(opt)
        for l in labels:
          parts.append(file_refs(l, True))
      for opt, name in (self.attr(t, 'outs', cfg) or {}).items():
        parts += [opt, '$(genDir)/%s/%s' % (pkg, name)]
      pos = self.attr(t, 'positional_srcs', cfg) or []
      if pos:
        parts.append('--')
        for l in pos:
          parts.append(file_refs(l, True))
      cmd = ' '.join(parts)

    m = collections.OrderedDict()
    m['name'] = mod_name(t.label)
    m['tools'] = tools
    m['tool_files'] = tool_files
    m['srcs'] = srcs
    m['out'] = outs
    m['cmd'] = cmd
    return m

  PY_EXTERNAL = {'@abseil-py': 'absl-py'}

  def py_libs(self, t, own_srcs):
    """Python deps of t; libraries whose sources t already has are
    replaced by their own deps (Soong rejects duplicated files)."""
    libs = []
    for item in self.attr(t, 'deps', 'host') or []:
      kind, val = self.classify(item, t.pkg)
      if kind == 'external':
        ext = self.PY_EXTERNAL.get(val.split('//')[0])
        if ext is None:
          raise ValueError('%s: unknown python dependency %s' % (t.label, val))
        if ext not in libs:
          libs.append(ext)
        continue
      if kind != 'target':
        continue
      lt = self.target(val)
      lsrcs = set()
      for f in self.attr(lt, 'srcs', 'host') or []:
        fk, fv = self.classify(f, lt.pkg)
        if fk == 'file':
          lsrcs.add(fv)
      if lsrcs and lsrcs <= own_srcs:
        for sub in self.py_libs(lt, own_srcs):
          if sub not in libs:
            libs.append(sub)
      elif mod_name(val) not in libs:
        libs.append(mod_name(val))
    return libs

  # ---- module emission ---------------------------------------------------
  def split_cfg(self, per_cfg, cfgs):
    """Splits per-config property dicts into common + target-specific."""
    common = collections.OrderedDict()
    specific = {c: collections.OrderedDict() for c in cfgs}
    keys = []
    for c in cfgs:
      for k in per_cfg[c]:
        if k not in keys:
          keys.append(k)
    for k in keys:
      vals = [per_cfg[c].get(k, []) for c in cfgs]
      if all(v == vals[0] for v in vals):
        common[k] = vals[0]
        continue
      shared = [x for x in vals[0] if all(x in v for v in vals[1:])]
      common[k] = shared
      for c, v in zip(cfgs, vals):
        rest = [x for x in v if x not in shared]
        if rest:
          specific[c][k] = rest
    return common, specific

  def finish_cc(self, m, per_cfg, cfgs):
    common, specific = self.split_cfg(per_cfg, cfgs)
    m.update(common)
    target = collections.OrderedDict()
    if 'device' in specific and specific['device']:
      target['android'] = specific['device']
    if 'host' in specific and specific['host']:
      target['host'] = specific['host']
    if 'device' not in cfgs:
      m['device_supported'] = False
    if 'host' not in cfgs:
      m['host_supported'] = False
    if target:
      m['target'] = target
    return m

  def fix_protobuf(self, props, cfg):
    """Replaces the @protobuf placeholder with the right library."""
    for key in ('static_libs', 'whole_static_libs'):
      libs = props.get(key, [])
      if '@protobuf' in libs:
        libs.remove('@protobuf')
        for exp in ('export_static_lib_headers',):
          if '@protobuf' in props.get(exp, []):
            props[exp].remove('@protobuf')
        if cfg == 'device':
          props.setdefault('static_libs', []).append('libprotobuf-cpp-full-ndk')
          props.setdefault('export_static_lib_headers', []).append('libprotobuf-cpp-full-ndk')
        else:
          props.setdefault('shared_libs', []).append('libprotobuf-cpp-full')
          props.setdefault('export_shared_lib_headers', []).append('libprotobuf-cpp-full')

  def emit_modules(self):
    mods = []
    for label in sorted(self.needed):
      t = self.target(label)
      cfgs = sorted(self.needed[label])
      k = t.kind
      if k == 'cc_library' or (k == 'cc_binary' and label != '//android/jni:mozc'):
        per_cfg = self.cc_module(t)
        for c in cfgs:
          self.fix_protobuf(per_cfg[c], c)
        m = collections.OrderedDict()
        if k == 'cc_library':
          m['_type'] = 'cc_library_static'
          m['name'] = mod_name(label)
          m['defaults'] = ['mozc_defaults']
          mods.append(self.finish_cc(m, per_cfg, cfgs))
        else:
          assert cfgs == ['host'], label
          m['_type'] = 'cc_binary_host'
          m['name'] = mod_name(label)
          m['defaults'] = ['mozc_host_binary_defaults']
          props = per_cfg['host']
          for exp in ('export_static_lib_headers', 'export_shared_lib_headers',
                      'export_generated_headers'):
            props.pop(exp, None)
          m.update(props)
          mods.append(m)
      elif label == '//android/jni:mozc':
        per_cfg = self.cc_module(t)
        props = per_cfg['device']
        self.fix_protobuf(props, 'device')
        m = collections.OrderedDict()
        m['_type'] = 'cc_library_shared'
        m['name'] = 'libmozc'
        m['defaults'] = ['mozc_jni_defaults']
        m['whole_static_libs'] = props['whole_static_libs']
        m['static_libs'] = props['static_libs']
        m['shared_libs'] = props['shared_libs']
        mods.append(m)
      elif k == 'proto_library':
        m = collections.OrderedDict()
        m['_type'] = 'cc_library_static'
        m['name'] = mod_name(label)
        m['defaults'] = ['mozc_proto_defaults']
        srcs = []
        for item in self.attr(t, 'srcs', cfgs[0]) or []:
          kind, val = self.classify(item, t.pkg)
          assert kind == 'file', (label, item)
          srcs.append(val)
        m['srcs'] = srcs
        deps = []
        for item in self.attr(t, 'deps', cfgs[0]) or []:
          kind, val = self.classify(item, t.pkg)
          if kind == 'target':
            deps.append(mod_name(val))
        m['static_libs'] = deps
        m['export_static_lib_headers'] = deps
        if 'device' not in cfgs:
          m['device_supported'] = False
        if 'host' not in cfgs:
          m['host_supported'] = False
        mods.append(m)
      elif k == 'cc_proto_library':
        continue  # folded into proto_library modules
      elif k in GEN_KINDS:
        m = self.gen_module(t)
        m['_type'] = 'genrule'
        m.move_to_end('_type', last=False)
        mods.append(m)
      elif k == 'py_binary' or k == 'py_library':
        m = collections.OrderedDict()
        m['_type'] = 'python_binary_host' if k == 'py_binary' else 'python_library_host'
        m['name'] = mod_name(label)
        srcs = []
        for item in self.attr(t, 'srcs', 'host') or []:
          kind, val = self.classify(item, t.pkg)
          assert kind == 'file', (label, item)
          srcs.append(val)
        if k == 'py_binary':
          main = t.attrs.get('main') or srcs[0]
          kind, val = self.classify(main, t.pkg)
          m['main'] = val
          if val not in srcs:
            srcs.insert(0, val)
        m['srcs'] = srcs
        m['libs'] = self.py_libs(t, set(srcs))
        mods.append(m)
      elif k == 'filegroup':
        continue
      else:
        raise ValueError('unsupported rule %s (%s)' % (label, k))
    self.link_transitively(mods)
    mods.insert(0, self.generated_defines())
    return mods

  def generated_defines(self):
    """Collects `defines` of all cc_library targets, per configuration."""
    per_cfg = {'device': set(), 'host': set()}
    for label, cfgs in self.needed.items():
      t = self.target(label)
      if t.kind != 'cc_library':
        continue
      for cfg in cfgs:
        for d in self.attr(t, 'defines', cfg) or []:
          per_cfg[cfg].add('-D' + d)
    m = collections.OrderedDict()
    m['_type'] = 'cc_defaults'
    m['name'] = 'mozc_generated_defines'
    target = collections.OrderedDict()
    if per_cfg['device']:
      target['android'] = {'cflags': sorted(per_cfg['device'])}
    if per_cfg['host']:
      target['host'] = {'cflags': sorted(per_cfg['host'])}
    m['target'] = target
    return m

  @staticmethod
  def link_transitively(mods):
    """Lists every transitive static library on binaries / libmozc.

    Bazel links the whole dependency closure; Soong only links the
    static_libs listed on the final module.
    """
    by_name = {m['name']: m for m in mods}

    def libs_of(m, target):
      out = []
      for d in (m, m.get('target', {}).get(target, {})):
        out += d.get('whole_static_libs', []) + d.get('static_libs', [])
      return out

    def shared_of(m, target):
      out = []
      for d in (m, m.get('target', {}).get(target, {})):
        out += d.get('shared_libs', [])
      return out

    for m in mods:
      if m['_type'] not in ('cc_binary_host', 'cc_library_shared'):
        continue
      target = 'host' if m['_type'] == 'cc_binary_host' else 'android'
      seen, order, shared = set(), [], list(shared_of(m, target))
      todo = list(libs_of(m, target))
      while todo:
        name = todo.pop(0)
        if name in seen:
          continue
        seen.add(name)
        order.append(name)
        dep = by_name.get(name)
        if dep is not None:
          todo += libs_of(dep, target)
          for sh in shared_of(dep, target):
            if sh not in shared:
              shared.append(sh)
      # Proto modules get the protobuf runtime implicitly from Soong, which
      # does not propagate it to the final link.
      if any(by_name.get(n, {}).get('defaults') == ['mozc_proto_defaults']
             for n in order):
        if target == 'host':
          if 'libprotobuf-cpp-full' not in shared:
            shared.append('libprotobuf-cpp-full')
        elif 'libprotobuf-cpp-full-ndk' not in order:
          order.append('libprotobuf-cpp-full-ndk')
      whole = m.get('whole_static_libs', [])
      m['static_libs'] = [n for n in order if n not in whole]
      m['shared_libs'] = shared
      m.pop('target', None)


# ---- Android.bp serialization ----------------------------------------------
def bp_value(v, indent):
  pad = '    ' * indent
  if isinstance(v, bool):
    return 'true' if v else 'false'
  if isinstance(v, str):
    return '"%s"' % v.replace('\\', '\\\\').replace('"', '\\"')
  if isinstance(v, list):
    if not v:
      return '[]'
    if len(v) == 1 and len(v[0]) < 60:
      return '[%s]' % bp_value(v[0], 0)
    return '[\n%s\n%s]' % (',\n'.join(pad + '    ' + bp_value(x, indent + 1) for x in v) + ',', pad)
  if isinstance(v, dict):
    lines = []
    for k, x in v.items():
      if x is None or (isinstance(x, (list, dict)) and not x):
        continue
      lines.append('%s    %s: %s,' % (pad, k, bp_value(x, indent + 1)))
    return '{\n%s\n%s}' % ('\n'.join(lines), pad)
  raise TypeError(v)


def bp_module(m):
  m = collections.OrderedDict(m)
  kind = m.pop('_type')
  return '%s %s\n' % (kind, bp_value(m, 0))


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument('--mozc_src', required=True)
  ap.add_argument('--out', required=True)
  ap.add_argument('--version', default='unknown')
  ap.add_argument('--prologue', help='Android.bp fragment to prepend')
  ap.add_argument('--list', action='store_true')
  ap.add_argument('--written_list',
                  help='write the list of files written into --out here')
  args = ap.parse_args()
  conv = Converter(os.path.abspath(args.mozc_src), args.version)
  conv.walk()
  if args.list:
    for label, cfgs in sorted(conv.needed.items()):
      print(conv.target(label).kind, label, sorted(cfgs))
    return
  mods = conv.emit_modules()
  out = os.path.abspath(args.out)
  # Copy the source files.
  files = set(conv.files)
  for m in mods:
    for key in ('srcs', 'main'):
      v = m.get(key)
      for f in ([v] if isinstance(v, str) else v or []):
        if not f.startswith(':') and not f.startswith('third_party/'):
          files.add(f)
  written = []

  def dest(rel):
    norm = os.path.normpath(rel)
    if os.path.isabs(rel) or norm.startswith('..'):
      raise ValueError('refusing to write outside --out: %r' % rel)
    written.append(norm)
    return os.path.join(out, norm)

  for f in sorted(files):
    if f.startswith('third_party/'):
      continue  # fetched by update_mozc.py
    dst = dest(f)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(os.path.join(conv.src, f), dst)
  with open(dest('Android.bp'), 'w', encoding='utf-8') as f:
    f.write(LICENSE_HEADER % args.version)
    if args.prologue:
      with open(args.prologue, encoding='utf-8') as p:
        f.write(p.read())
    for m in mods:
      f.write('\n')
      f.write(bp_module(m))
  if args.written_list:
    with open(args.written_list, 'w', encoding='utf-8') as f:
      f.write(''.join(w + '\n' for w in written))
  print('%d modules, %d files' % (len(mods), len(files)))


if __name__ == '__main__':
  main()
